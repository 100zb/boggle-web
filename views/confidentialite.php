    <h1>Tes données personnelles</h1>

    <h2>Qui est responsable ?</h2>
    <p>Ce site est un projet étudiant (SAÉ S3, BUT Informatique, IUT de Marne-la-Vallée, Université Gustave Eiffel). Il n'a pas de but commercial.</p>

    <h2>Quelles données, et pourquoi ?</h2>
    <ul>
        <li><strong>Pseudo et mot de passe</strong> (obligatoires) : pour créer ton compte et te connecter. Le mot de passe n'est jamais stocké : on garde seulement une empreinte (hash) qui ne permet pas de le retrouver.</li>
        <li><strong>Email</strong> (facultatif) : uniquement pour t'envoyer un lien si tu oublies ton mot de passe. Il est chiffré dans la base.</li>
        <li><strong>Parties, scores et messages du chat</strong> : pour faire fonctionner le jeu et afficher ton historique.</li>
        <li><strong>Tentatives de connexion ratées</strong> (pseudo tapé et adresse IP transformée par un calcul à sens unique) : pour bloquer les attaques qui essaient des mots de passe en boucle. Effacées au bout d'un jour.</li>
    </ul>
    <p>La base légale est ton consentement, donné à l'inscription. Ton profil est privé par défaut.</p>

    <h2>Combien de temps ?</h2>
    <ul>
        <li>Compte sans connexion depuis 2 ans : anonymisé.</li>
        <li>Messages du chat : effacés au bout d'un an.</li>
        <li>Lien de changement de mot de passe : valable 30 minutes.</li>
    </ul>

    <h2>Qui y a accès ?</h2>
    <p>Personne d'autre que l'équipe du projet. Hébergement : Render (site) et Neon (base de données), serveurs en Europe (Francfort). L'envoi des emails passe par Brevo. Aucun cookie publicitaire ni outil de mesure d'audience : le seul cookie sert à garder ta session ouverte.</p>

    <h2>Tes droits</h2>
    <p>Tu peux demander à consulter tes données, les corriger, les récupérer ou supprimer ton compte. Pour cela, contacte l'équipe du projet. Tu peux aussi saisir la <a href="https://www.cnil.fr/fr/plaintes">CNIL</a>.</p>

